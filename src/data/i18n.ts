const dicts: Record<UiLang, Dict> = { en, uz, ru };

/**
 * Tanlangan til uchun tarjima funksiyasini qaytaradi.
 * {key} — tarjima kaliti; {var} ko'rinishidagi qismlar vars orqali almashtiriladi.
 * Topilmasa inglizcha, u ham bo'lmasa kalitning o'zi qaytadi.
 */
export function getT(lang: string) {
  const l: UiLang = UI_LANGS.includes(lang as UiLang) ? (lang as UiLang) : "en";
  const d = dicts[l];
  return (key: string, vars?: Record<string, string | number>): string => {
    let s = d[key] ?? dicts.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
}
